import { test, expect, type Page } from '@playwright/test'

test('demo messaging, search, saved messages and settings work', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Your conversations. Yours only.' })).toBeVisible()
  await page.getByRole('textbox', { name: 'Message', exact: true }).fill('A private little test message')
  await page.getByRole('button', { name: 'Send message', exact: true }).click()
  await expect(page.locator('.message-bubble').filter({ hasText: 'A private little test message' })).toBeVisible()
  await page.getByRole('button', { name: 'Search this conversation', exact: true }).click()
  await page.getByRole('textbox', { name: 'Search messages', exact: true }).fill('private little')
  await expect(page.locator('.message-row')).toHaveCount(1)
  await page.getByRole('button', { name: 'Close message search' }).click()
  const bubble = page.locator('.message-row').filter({ hasText: 'A private little test message' })
  await bubble.hover()
  await bubble.getByRole('button', { name: 'Save message', exact: true }).click()
  await page.getByRole('navigation', { name: 'Main navigation', exact: true }).getByRole('button', { name: 'Saved messages' }).click()
  await expect(page.locator('.saved-card').filter({ hasText: 'A private little test message' })).toBeVisible()
  await page.getByRole('navigation', { name: 'Preferences', exact: true }).getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByRole('switch', { name: 'Hide message previews', exact: true }).click()
  await page.getByRole('navigation', { name: 'Main navigation', exact: true }).getByRole('button', { name: 'Messages', exact: false }).first().click()
  await expect(page.getByText('Message preview hidden').first()).toBeVisible()
})

test('toolkit encrypts and decrypts a note entirely locally', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('navigation', { name: 'Main navigation', exact: true }).getByRole('button', { name: 'Privacy toolkit', exact: false }).click()
  await page.getByRole('button', { name: 'Text lock', exact: false }).click()
  await page.getByLabel('Your message', { exact: true }).fill('A secret in a local vault')
  await page.getByLabel('Passphrase', { exact: true }).fill('a long test passphrase 123')
  await page.getByRole('button', { name: 'Encrypt text', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Tool result', exact: true })).toBeVisible()
  const box = await page.getByRole('textbox', { name: 'Tool result', exact: true }).inputValue()
  expect(box).not.toContain('A secret in a local vault')
  await page.getByRole('button', { name: 'Decrypt', exact: true }).click()
  await page.getByLabel('Encrypted vault data', { exact: true }).fill(box)
  await page.getByRole('button', { name: 'Decrypt text', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Tool result', exact: true })).toHaveValue('A secret in a local vault')
  await page.getByRole('button', { name: 'Close dialog', exact: true }).click()
})

