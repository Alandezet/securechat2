async function signup(page: Page, name: string, username: string) {
  await page.goto('/')
  await page.getByRole('button', { name: 'Make it yours', exact: true }).click()
  await page.getByLabel('Your name', { exact: true }).fill(name)
  await page.getByLabel('Username', { exact: true }).fill(username)
  await page.getByLabel('Passphrase', { exact: true }).fill('e2e secret passphrase 2026')
  await page.getByLabel('Confirm passphrase', { exact: true }).fill('e2e secret passphrase 2026')
  await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: 'Create your free account', exact: true }).click()
  await expect(page.locator('.auth-modal')).toBeHidden({ timeout: 30000 })
  await expect(page.locator('.connection-badge')).toHaveText('Connected', { timeout: 20000 })
}

test('two accounts exchange encrypted live messages, upload photos, verify keys, and unlock after locking', async ({ browser }) => {
  const aContext = await browser.newContext(), bContext = await browser.newContext()
  try {
    const a = await aContext.newPage(), b = await bContext.newPage()
    const suffix = Date.now().toString(36)
    const alice = `alice_${suffix}`, bob = `bob_${suffix}`
    await signup(a, 'Alice Test', alice)
    await signup(b, 'Bob Test', bob)
    await a.getByRole('button', { name: 'New conversation', exact: true }).click()
    await a.getByRole('textbox', { name: 'Find contact by username', exact: true }).fill(bob)
    await a.locator('.contact-result').filter({ hasText: 'Bob Test' }).click()
    await a.getByRole('textbox', { name: 'Message', exact: true }).fill('Real encrypted hello from Alice')
    await a.getByRole('button', { name: 'Send message', exact: true }).click()
    await expect(b.locator('.conversation-item').filter({ hasText: 'Alice Test' })).toBeVisible({ timeout: 20000 })
    await b.locator('.conversation-item').filter({ hasText: 'Alice Test' }).click()
    await expect(b.locator('.message-bubble').filter({ hasText: 'Real encrypted hello from Alice' })).toBeVisible()
    await b.getByRole('textbox', { name: 'Message', exact: true }).fill('And an encrypted reply from Bob')
    await b.getByRole('button', { name: 'Send message', exact: true }).click()
    await expect(a.locator('.message-bubble').filter({ hasText: 'And an encrypted reply from Bob' })).toBeVisible({ timeout: 10000 })
    await a.locator('input[type=file][accept="image/jpeg,image/png,image/webp"]').setInputFiles('web/public/images/alpine-lake.jpg')
    await expect(a.locator('.attachment-preview')).toBeVisible({ timeout: 20000 })
    await a.getByRole('button', { name: 'Send message', exact: true }).click()
    await expect(b.locator('.message-photo img')).toBeVisible({ timeout: 10000 })
    if (!await a.locator('.conversation-details').isVisible()) await a.getByRole('button', { name: 'Conversation details', exact: true }).click()
    await a.locator('.contact-quick-actions').getByRole('button', { name: 'Verify', exact: true }).click()
    await expect(a.locator('.fingerprint-grid code')).toHaveCount(16)
    await a.getByRole('checkbox').check()
    await a.getByRole('button', { name: 'Mark identity as verified', exact: true }).click()
    const storage = await a.evaluate(() => JSON.stringify(localStorage))
    expect(storage).not.toContain('Real encrypted hello from Alice')
    expect(storage).not.toContain('And an encrypted reply from Bob')
    await a.getByRole('button', { name: 'Lock your account', exact: true }).click()
    await expect(a.getByRole('heading', { name: 'Welcome back.', exact: true })).toBeVisible()
    await a.getByLabel('Passphrase', { exact: true }).fill('e2e secret passphrase 2026')
    await a.getByRole('button', { name: 'Unlock your space', exact: true }).click()
    await expect(a.locator('.conversation-item').filter({ hasText: 'Bob Test' })).toBeVisible({ timeout: 20000 })
    await a.locator('.conversation-item').filter({ hasText: 'Bob Test' }).click()
    await expect(a.locator('.message-bubble').filter({ hasText: 'And an encrypted reply from Bob' })).toBeVisible()
  } finally { await aContext.close().catch(() => {}); await bContext.close().catch(() => {}) }
})
